/**
 * Normalizes role string to match seed banks
 */
export function getRoleValidationBank(targetRole: string): RoleValidationBank {
  const normalized = targetRole.trim().toLowerCase();

  for (const [key, bank] of Object.entries(SEED_ROLE_BANKS)) {
    if (normalized.includes(key) || key.includes(normalized)) {
      return bank;
    }
  }

  // Keyword fallbacks
  if (normalized.includes('backend') || normalized.includes('python') || normalized.includes('node') || normalized.includes('developer') || normalized.includes('software') || normalized.includes('engineer')) {
    return SEED_ROLE_BANKS['python backend developer'];
  }
  if (normalized.includes('analyst') || normalized.includes('data') || normalized.includes('bi ') || normalized.includes('analytics')) {
    return SEED_ROLE_BANKS['data analyst'];
  }
  if (normalized.includes('sales') || normalized.includes('biz') || normalized.includes('business development') || normalized.includes('growth')) {
    return SEED_ROLE_BANKS['sales'];
  }

  // Generic fallback using target role name
  return {
    targetRole: targetRole || 'Target Career Professional',
    knowledgeQuestions: [
      {
        dimension: 'Knowledge Depth',
        assessmentType: 'Knowledge',
        prompt: `To start your Capability Validation for **${targetRole}**, let’s begin with core conceptual depth:\n\n**Can you explain one fundamental concept or tool vital to ${targetRole}, how it works, and when it should or should not be used?**`,
        expectedCriteria: `Candidate demonstrates deep conceptual understanding of tools and principles critical to ${targetRole}.`,
      },
    ],
    reasoningQuestions: [
      {
        dimension: 'Problem Solving',
        assessmentType: 'Problem Solving',
        prompt: `**Reasoning & Scenario Analysis:**\n\nSuppose you encounter an unfamiliar, high-stakes problem or failure in your work as a **${targetRole}**. Walk me through your step-by-step methodology to analyze the issue, evaluate trade-offs, and deliver a reliable solution.`,
        expectedCriteria: `Systematic problem-solving methodology, trade-off evaluation, and verifiable quality assurance.`,
      },
    ],
    practicalTask: {
      taskTitle: `Complete a core practical deliverable for ${targetRole}`,
      taskDescription: `Submit an artifact, code repository, analytical report, or project documentation demonstrating your practical execution capabilities as a ${targetRole}.`,
      requiredEvidence: `Work artifact (link, repository, or document summary), assistance declaration, and explanation of individual contribution.`,
      acceptanceCriteria: [
        'Demonstrates practical execution meeting professional standards',
        'Transparent disclosure of external tools or AI assistance',
        'Clear explanation of decisions and personal ownership',
      ],
    },
  };
}

/**
 * Checks if the user's message indicates skipping or lacking a practical project
 */
export function isDecliningPracticalTask(userMessage: string): boolean {
  const text = userMessage.toLowerCase().trim();

  // Explicit decline / skip / partial keywords
  if (
    text.includes('partial') ||
    text.includes("don't have") ||
    text.includes('dont have') ||
    text.includes('do not have') ||
    text.includes('no project') ||
    text.includes('no deliverable') ||
    text.includes('no repo') ||
    text.includes('no code') ||
    text.includes('skip') ||
    text.includes('not yet') ||
    text.includes('later') ||
    text.includes('cannot submit') ||
    text.includes("can't submit") ||
    text.includes('cant submit') ||
    text.includes("haven't built") ||
    text.includes('havent built') ||
    text.includes('have not built') ||
    text.includes('no practical') ||
    text.includes('none')
  ) {
    return true;
  }

  // Check if they provided any link or code snippet
  const hasUrl =
    text.includes('http://') ||
    text.includes('https://') ||
    text.includes('github.com') ||
    text.includes('gitlab.com');
  const hasCodeOrSchema =
    text.includes('```') ||
    text.includes('def ') ||
    text.includes('class ') ||
    text.includes('create table') ||
    text.includes('import ') ||
    text.includes('router.') ||
    text.includes('app.') ||
    text.includes('fastapi') ||
    text.includes('flask');

  // If the message is short (< 35 chars) and contains no link or code snippet, treat as partial
  if (!hasUrl && !hasCodeOrSchema && text.length < 35) {
    return true;
  }

  return false;
}
